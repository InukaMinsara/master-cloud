import React, { useState } from 'react';
import {
  Sparkles,
  Wand2,
  Send,
  X,
  Check,
  Copy,
  RefreshCw,
  Languages,
  FileText,
  ListChecks,
  Minimize2,
  Maximize2,
  Replace,
  CornerDownLeft,
} from 'lucide-react';
import { AIService } from '@/services/aiService';
import { Button } from '@/components/ui/button';
import { toast } from 'sonner';

interface MasterDocsAICopilotProps {
  isOpen: boolean;
  onClose: () => void;
  documentTitle: string;
  documentHtml: string;
  selectedText: string;
  onInsertHtml: (html: string) => void;
  onReplaceSelectionHtml: (html: string) => void;
}

/**
 * Converts clean Markdown generated by Master AI Core into Word-ready HTML.
 */
function markdownToDocHtml(md: string): string {
  const lines = md.replace(/\r\n/g, '\n').split('\n');
  const html: string[] = [];
  let inUl = false;
  let inOl = false;

  const formatInline = (txt: string) =>
    txt
      .replace(/&/g, '&amp;')
      .replace(/</g, '&lt;')
      .replace(/>/g, '&gt;')
      .replace(/\*\*(.+?)\*\*/g, '<strong>$1</strong>')
      .replace(/\*(.+?)\*/g, '<em>$1</em>')
      .replace(/`([^`]+)`/g, '<code>$1</code>');

  const closeLists = () => {
    if (inUl) {
      html.push('</ul>');
      inUl = false;
    }
    if (inOl) {
      html.push('</ol>');
      inOl = false;
    }
  };

  for (const rawLine of lines) {
    const line = rawLine.trim();
    if (!line) {
      closeLists();
      continue;
    }

    if (line.startsWith('### ')) {
      closeLists();
      html.push(`<h3>${formatInline(line.slice(4))}</h3>`);
    } else if (line.startsWith('## ')) {
      closeLists();
      html.push(`<h2>${formatInline(line.slice(3))}</h2>`);
    } else if (line.startsWith('# ')) {
      closeLists();
      html.push(`<h1>${formatInline(line.slice(2))}</h1>`);
    } else if (/^[-*•]\s+/.test(line)) {
      if (inOl) {
        html.push('</ol>');
        inOl = false;
      }
      if (!inUl) {
        html.push('<ul>');
        inUl = true;
      }
      html.push(`<li>${formatInline(line.replace(/^[-*•]\s+/, ''))}</li>`);
    } else if (/^\d+\.\s+/.test(line)) {
      if (inUl) {
        html.push('</ul>');
        inUl = false;
      }
      if (!inOl) {
        html.push('<ol>');
        inOl = true;
      }
      html.push(`<li>${formatInline(line.replace(/^\d+\.\s+/, ''))}</li>`);
    } else if (line.startsWith('> ')) {
      closeLists();
      html.push(`<blockquote>${formatInline(line.slice(2))}</blockquote>`);
    } else {
      closeLists();
      html.push(`<p>${formatInline(line)}</p>`);
    }
  }
  closeLists();
  return html.join('');
}

export function MasterDocsAICopilot({
  isOpen,
  onClose,
  documentTitle,
  documentHtml,
  selectedText,
  onInsertHtml,
  onReplaceSelectionHtml,
}: MasterDocsAICopilotProps) {
  const [prompt, setPrompt] = useState('');
  const [output, setOutput] = useState('');
  const [isStreaming, setIsStreaming] = useState(false);

  if (!isOpen) return null;

  const getPlainDocExcerpt = () => {
    const tmp = document.createElement('div');
    tmp.innerHTML = documentHtml;
    return (tmp.innerText || tmp.textContent || '').trim().slice(0, 3500);
  };

  const runCopilotPrompt = async (instruction: string, useSelectionFirst = true) => {
    if (!instruction.trim() || isStreaming) return;
    setIsStreaming(true);
    setOutput('');

    const contextTarget = useSelectionFirst && selectedText.trim()
      ? `Selected text:\n"""\n${selectedText.trim()}\n"""`
      : `Current document ("${documentTitle}"):\n"""\n${getPlainDocExcerpt()}\n"""`;

    const fullPrompt = `You are Copilot inside Microsoft Word / Master Cloud Docs. Return clean, well-structured Markdown ready to insert into the document (no meta-commentary).\n\n${contextTarget}\n\nInstruction: ${instruction}`;

    try {
      let latest = '';
      for await (const chunk of AIService.streamResponse(fullPrompt, [], null, 'writer')) {
        latest = chunk;
        setOutput(chunk);
      }
      if (!latest.trim()) {
        setOutput('No output generated. Please try rephrasing your request.');
      }
    } catch (err: any) {
      toast.error('Copilot failed: ' + (err?.message || 'AI Gateway error'));
    } finally {
      setIsStreaming(false);
    }
  };

  const quickActions = [
    {
      label: 'Polish & Rewrite',
      icon: Wand2,
      color: 'text-blue-600',
      action: () => runCopilotPrompt('Rewrite and polish this text to sound clear, professional, and engaging.'),
    },
    {
      label: 'Fix Grammar',
      icon: Check,
      color: 'text-emerald-600',
      action: () => runCopilotPrompt('Fix all spelling, punctuation, and grammar mistakes while preserving meaning.'),
    },
    {
      label: 'Summarize',
      icon: ListChecks,
      color: 'text-indigo-600',
      action: () => runCopilotPrompt('Create a concise bullet-point executive summary of this content.', false),
    },
    {
      label: 'Make Concise',
      icon: Minimize2,
      color: 'text-amber-600',
      action: () => runCopilotPrompt('Shorten and condense this text while keeping all key facts.'),
    },
    {
      label: 'Expand Detail',
      icon: Maximize2,
      color: 'text-purple-600',
      action: () => runCopilotPrompt('Expand this text with richer explanation, structured headings, and examples.'),
    },
    {
      label: 'To Sinhala',
      icon: Languages,
      color: 'text-rose-600',
      action: () => runCopilotPrompt('Translate this content accurately into natural Sinhala.'),
    },
    {
      label: 'To English',
      icon: Languages,
      color: 'text-cyan-600',
      action: () => runCopilotPrompt('Translate this content accurately into natural professional English.'),
    },
    {
      label: 'Draft Outline',
      icon: FileText,
      color: 'text-sky-600',
      action: () => runCopilotPrompt(`Draft a structured Word document outline for "${documentTitle || 'this topic'}".`, false),
    },
  ];

  const handleInsert = () => {
    if (!output.trim()) return;
    onInsertHtml(markdownToDocHtml(output));
    toast.success('Inserted Copilot draft into document');
  };

  const handleReplace = () => {
    if (!output.trim()) return;
    onReplaceSelectionHtml(markdownToDocHtml(output));
    toast.success('Replaced selection with Copilot output');
  };

  return (
    <aside className="w-80 sm:w-96 border-l border-border/80 bg-card/95 backdrop-blur-xl flex flex-col shrink-0 z-20 select-none">
      {/* Header */}
      <div className="flex items-center justify-between px-4 py-3 border-b border-border/70 bg-gradient-to-r from-[#185abd]/10 to-indigo-500/10">
        <div className="flex items-center gap-2">
          <div className="h-7 w-7 rounded-lg bg-[#185abd] text-white flex items-center justify-center shadow-sm">
            <Sparkles className="h-4 w-4" />
          </div>
          <div>
            <h3 className="text-xs font-bold text-foreground">Docs Copilot</h3>
            <p className="text-[10px] text-muted-foreground">Powered by Master AI Core</p>
          </div>
        </div>
        <button
          onClick={onClose}
          className="p-1.5 rounded-lg text-muted-foreground hover:bg-accent hover:text-foreground transition-colors"
          title="Close Copilot"
        >
          <X className="h-4 w-4" />
        </button>
      </div>

      {/* Body */}
      <div className="flex-1 overflow-y-auto p-4 space-y-4">
        {/* Selection Context Badge */}
        <div className="rounded-xl border border-border/80 bg-muted/40 p-2.5 text-[11px]">
          <div className="font-semibold text-foreground flex items-center justify-between mb-1">
            <span>Context Scope</span>
            <span className="text-[10px] px-1.5 py-0.5 rounded bg-primary/15 text-primary font-bold">
              {selectedText ? 'Selected Text' : 'Full Document'}
            </span>
          </div>
          <p className="text-muted-foreground line-clamp-2 italic">
            {selectedText ? `"${selectedText}"` : `Using "${documentTitle || 'Untitled Document'}"`}
          </p>
        </div>

        {/* Quick Actions Grid */}
        <div className="space-y-2">
          <div className="text-[10px] font-bold uppercase tracking-wider text-muted-foreground">
            One-Click Writing Tools
          </div>
          <div className="grid grid-cols-2 gap-1.5">
            {quickActions.map((qa) => (
              <button
                key={qa.label}
                disabled={isStreaming}
                onClick={qa.action}
                className="flex items-center gap-1.5 px-2.5 py-2 rounded-xl border border-border/70 bg-background hover:bg-accent hover:border-[#185abd]/40 text-left text-[11px] font-semibold transition-all disabled:opacity-50"
              >
                <qa.icon className={`h-3.5 w-3.5 shrink-0 ${qa.color}`} />
                <span className="truncate">{qa.label}</span>
              </button>
            ))}
          </div>
        </div>

        {/* Streaming Output Area */}
        {(output || isStreaming) && (
          <div className="space-y-2 pt-2 border-t border-border/60">
            <div className="flex items-center justify-between">
              <span className="text-[10px] font-bold uppercase tracking-wider text-muted-foreground">
                {isStreaming ? 'Copilot is drafting...' : 'Generated Draft'}
              </span>
              {output && !isStreaming && (
                <button
                  onClick={() => {
                    navigator.clipboard.writeText(output);
                    toast.success('Copied to clipboard');
                  }}
                  className="text-[11px] text-muted-foreground hover:text-foreground flex items-center gap-1"
                >
                  <Copy className="h-3 w-3" /> Copy
                </button>
              )}
            </div>

            <div className="rounded-xl border border-border bg-background p-3 text-xs leading-relaxed text-foreground whitespace-pre-wrap max-h-64 overflow-y-auto select-text">
              {output || (
                <span className="flex items-center gap-2 text-muted-foreground">
                  <RefreshCw className="h-3.5 w-3.5 animate-spin" /> Thinking...
                </span>
              )}
            </div>

            {output && !isStreaming && (
              <div className="flex items-center gap-2">
                <Button
                  size="sm"
                  onClick={handleInsert}
                  className="flex-1 bg-[#185abd] hover:bg-[#144a9c] text-white text-xs h-8 rounded-xl gap-1.5 font-semibold"
                >
                  <CornerDownLeft className="h-3.5 w-3.5" /> Insert at Cursor
                </Button>
                {selectedText && (
                  <Button
                    size="sm"
                    variant="outline"
                    onClick={handleReplace}
                    className="flex-1 text-xs h-8 rounded-xl gap-1.5 font-semibold"
                  >
                    <Replace className="h-3.5 w-3.5" /> Replace
                  </Button>
                )}
              </div>
            )}
          </div>
        )}
      </div>

      {/* Bottom Prompt Input */}
      <form
        onSubmit={(e) => {
          e.preventDefault();
          runCopilotPrompt(prompt);
          setPrompt('');
        }}
        className="p-3 border-t border-border/80 bg-muted/30 space-y-2"
      >
        <div className="flex items-end gap-1.5">
          <textarea
            value={prompt}
            onChange={(e) => setPrompt(e.target.value)}
            onKeyDown={(e) => {
              if (e.key === 'Enter' && !e.shiftKey) {
                e.preventDefault();
                runCopilotPrompt(prompt);
                setPrompt('');
              }
            }}
            rows={2}
            placeholder="Ask Copilot to draft a letter, report, table..."
            className="flex-1 resize-none rounded-xl border border-border bg-background px-3 py-2 text-xs text-foreground placeholder:text-muted-foreground focus:outline-none focus:ring-1 focus:ring-[#185abd]"
          />
          <Button
            type="submit"
            disabled={isStreaming || !prompt.trim()}
            size="sm"
            className="h-9 w-9 p-0 rounded-xl bg-[#185abd] hover:bg-[#144a9c] text-white shrink-0"
            title="Send to Copilot"
          >
            {isStreaming ? <RefreshCw className="h-4 w-4 animate-spin" /> : <Send className="h-4 w-4" />}
          </Button>
        </div>
      </form>
    </aside>
  );
}
