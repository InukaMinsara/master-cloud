  static darkenHex(hex: string, factor = 0.74): string {
    const clean = hex.replace('#', '');
    if (clean.length !== 6) return hex;
    const r = Math.max(0, Math.min(255, Math.round(parseInt(clean.slice(0, 2), 16) * factor)));
    const g = Math.max(0, Math.min(255, Math.round(parseInt(clean.slice(2, 4), 16) * factor)));
    const b = Math.max(0, Math.min(255, Math.round(parseInt(clean.slice(4, 6), 16) * factor)));
    return `#${r.toString(16).padStart(2, '0')}${g.toString(16).padStart(2, '0')}${b.toString(16).padStart(2, '0')}`;
  }

  static lightenHexTint(hex: string, weight = 0.9): string {
    const clean = hex.replace('#', '');
    if (clean.length !== 6) return '#eef5f9';
    const r = Math.round(parseInt(clean.slice(0, 2), 16) * (1 - weight) + 255 * weight);
    const g = Math.round(parseInt(clean.slice(2, 4), 16) * (1 - weight) + 255 * weight);
    const b = Math.round(parseInt(clean.slice(4, 6), 16) * (1 - weight) + 255 * weight);
    return `#${r.toString(16).padStart(2, '0')}${g.toString(16).padStart(2, '0')}${b.toString(16).padStart(2, '0')}`;
  }

